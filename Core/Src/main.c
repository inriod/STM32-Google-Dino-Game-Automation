/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM4_Init();
  MX_I2C1_Init();
  /* USER CODE BEGIN 2 */

  HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_3); // jump servo
  HAL_TIM_PWM_Start(&htim4, TIM_CHANNEL_4); // duck servo
  TIM4->CCR3 = jumpRest;
  TIM4->CCR4 = duckRest;

  ssd1306_Init();

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	  if (HAL_GetTick() - lastBlink >= (mode ? 100 : 500)) // Auto mode : slow, Guitar mode : fast
	  {
		  lastBlink = HAL_GetTick();
		  HAL_GPIO_TogglePin(LED_GPIO_Port, LED_Pin);
	  }

	  // Test if mode has been changed

	  if (mode != oldMode)
	  {
		  if (mode == 1)
		  {
			  jumps = 0;
			  ducks = 0;
			  updateScreen = 1;
		  }
		  oldMode = mode;
	  }

	  // Test in guitar mode each servo presses every 500ms taking turns
	  if (mode == 1 && HAL_GetTick() - lastTest > 500)
	  {
		  if (nextServo == 1)
		  {
			  TIM4->CCR3 = jumpPress;
			  jumpPressed = 1;
			  jumpTime = HAL_GetTick();
			  nextServo = 2;
			  jumps++;
			  updateScreen = 1;
		  }
		  else
		  {
			  TIM4->CCR4 = duckPress;
			  duckPressed = 1;
			  duckTime = HAL_GetTick();
			  nextServo = 1;
			  ducks++;
			  updateScreen = 1;
		  }
		  lastTest = HAL_GetTick();
	  }

	  // Release jump after 200 ms
	  if (jumpPressed == 1 && HAL_GetTick() - jumpTime > 200)
	  {
		  TIM4->CCR3 = jumpRest;
		  jumpPressed = 0;
	  }

	  // Release duck after 300 ms
	  if (duckPressed == 1 && HAL_GetTick() - duckTime > 300)
	  {
		  TIM4->CCR4 = duckRest;
		  duckPressed = 0;
	  }

	  // Redraw the screen
	  if (updateScreen == 1)
	  {
		  ssd1306_Fill(Black);

		  sprintf(text, "Jumps: %d", jumps);
		  ssd1306_SetCursor(0, 10);
		  ssd1306_WriteString(text, Font_11x18, White);

		  sprintf(text, "Ducks: %d", ducks);
		  ssd1306_SetCursor(0, 36);
		  ssd1306_WriteString(text, Font_11x18, White);

		  ssd1306_UpdateScreen();
		  updateScreen = 0;
	  }

  }
  /* USER CODE END 3 */
}

